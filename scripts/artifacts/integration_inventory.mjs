import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const data=JSON.parse(await fs.readFile(path.join(root,'integrations/projects.json'),'utf8'));
const out=path.join(root,'outputs/01a1a206-0159-7d73-836a-2c0d96ac52d4');
await fs.mkdir(out,{recursive:true});
const wb=Workbook.create();
const sheet=wb.worksheets.add('项目清单');
sheet.showGridLines=false;
sheet.tabColor='#6754BC';
sheet.getRange('A2').values=[['观潮系统项目接入清单']];
sheet.getRange('A2').format.font={name:'Arial',size:15,bold:true,color:'#222A38'};
sheet.getRange('A3').values=[['核验日期']];
sheet.getRange('B3').values=[[new Date(data.as_of+'T00:00:00Z')]];
sheet.getRange('B3').setNumberFormat('yyyy-mm-dd');
sheet.getRange('D3:E3').values=[['纳入项目','排除项目']];
sheet.getRange('D4:E4').formulas=[['=COUNTIFS(F8:F18,"纳入")','=COUNTIFS(F8:F18,"排除")']];
const status={pending:'待接入',integrated:'已接入',reference:'资料归档',excluded:'按要求排除',awaiting_key:'已接入 · 待填 Key'};
const source={awaiting_access:'待本机 GitHub 授权',fetched:'已拉取并锁定版本',public:'公开',api:'需配置 API Key',vendored:'已收录源码',excluded:'不拉取'};
const headers=['项目','用途','主要能力','输入','输出','范围','当前接入','源码 / 凭据','来源'];
const rows=data.projects.map(p=>[p.name,p.role,p.features,p.input,p.output,p.included?'纳入':'排除',status[p.integration_status]||p.integration_status,source[p.source_status]||p.source_status,p.repository]);
sheet.getRange('A7:I7').values=[headers];
sheet.getRange('A8:I18').values=rows;
sheet.getRange('A3:I18').format.font={name:'Arial',size:10,color:'#2B3442'};
sheet.getRange('A7:I7').format={fill:'#35405A',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},horizontalAlignment:'center',verticalAlignment:'center',rowHeight:28};
sheet.getRange('A8:I18').format={verticalAlignment:'center',wrapText:true,rowHeight:46};
const widths=[35,18,54,28,34,11,16,26,57];
for(let i=0;i<widths.length;i++)sheet.getRangeByIndexes(0,i,19,1).format.columnWidth=widths[i];
for(let i=0;i<rows.length;i++)if(i%2===0)sheet.getRangeByIndexes(7+i,0,1,9).format.fill='#F6F7FA';
sheet.getRange('F8:H18').conditionalFormats.add('containsText',{text:'待',format:{font:{color:'#9A6226'},fill:'#FFF5E7'}});
sheet.getRange('F8:F18').conditionalFormats.add('containsText',{text:'排除',format:{font:{color:'#727D8C'}}});
sheet.freezePanes.freezeRows(7);
sheet.freezePanes.freezeColumns(1);
sheet.tables.add('A7:I18',true,'ProjectInventory').showFilterButton=true;
const api=wb.worksheets.add('接口与依赖');
api.showGridLines=false;
api.getRange('A2').values=[['桥接与数据流']];
api.getRange('A2').format.font={name:'Arial',size:15,bold:true,color:'#222A38'};
api.getRange('A4:E4').values=[['项目','桥接方式','上游依赖','核验状态','来源']];
api.getRange('A5:E15').values=data.projects.map(p=>[p.name,p.bridge,p.depends_on.map(id=>data.projects.find(x=>x.id===id)?.name||id).join('、')||'无 / 本机独立运行',p.verification||source[p.source_status],p.repository]);
api.getRange('A4:E15').format={font:{name:'Arial',size:10,color:'#2B3442'},verticalAlignment:'center',wrapText:true,rowHeight:46};
api.getRange('A4:E4').format={fill:'#35405A',font:{bold:true,color:'#FFFFFF'},horizontalAlignment:'center',rowHeight:28};
[35,65,35,54,65].forEach((w,i)=>api.getRangeByIndexes(0,i,18,1).format.columnWidth=w);
api.getRange('A17:B17').values=[['TikHub 计费来源','https://tikhub.io/zh/pricing#plans']];
api.getRange('A18:B18').values=[['播放统计文档','https://docs.tikhub.io/186826221e0']];
api.getRange('A19:B19').values=[['星图播放量文档','https://docs.tikhub.io/493289600e0']];
api.freezePanes.freezeRows(4);
wb.recalculate();
const checks=await wb.inspect({kind:'table',range:'项目清单!D3:H4',include:'values,formulas',tableMaxRows:2,tableMaxCols:5});
console.log(checks.ndjson);
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:10}});
console.log(errors.ndjson);
for(const [name,range]of [['项目清单','A1:H18'],['接口与依赖','A1:D15']]){
 const preview=await wb.render({sheetName:name,range,scale:1,format:'png'});
 await fs.writeFile(path.join(out,name+'.png'),new Uint8Array(await preview.arrayBuffer()));
}
const xlsx=await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(path.join(out,'项目接入清单.xlsx'));
console.log('Workbook exported: '+path.join(out,'项目接入清单.xlsx'));
